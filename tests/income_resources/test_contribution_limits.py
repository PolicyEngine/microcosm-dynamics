def test_annual_irs_announcements_are_pinned_for_every_year():
    """The transcribed rows have IRS annual announcements for 2002--2026."""
    directory = (
        Path(__file__).resolve().parents[2]
        / "data"
        / "external"
        / "income_resources/retirement_rules_v1/contributions"
    )
    parameters = json.loads((directory / "parameters.json").read_text())
    captures = {
        row["file"]: row
        for row in json.loads(
            (directory / "capture_manifest.json").read_text()
        )
        if row["status"] == "captured"
    }
    announcements = parameters["annual_announcements"]
    assert set(announcements) == {str(year) for year in range(2002, 2027)}
    for source in announcements.values():
        capture = captures[source["file"]]
        content = (directory / source["file"]).read_bytes()
        assert content.startswith(b"%PDF")
        assert len(content) == capture["bytes"]
        assert hashlib.sha256(content).hexdigest() == capture["sha256"]


