@given(
    rises=st.lists(st.integers(1, 30), min_size=1, max_size=6),
    drops=st.lists(st.integers(1, 60), min_size=1, max_size=6),
    recoveries=st.lists(st.integers(0, 30), max_size=6),
    kind=st.sampled_from(list(HIGH_WATER_BASES)),
)
def test_deflation_keeps_every_reached_ceiling(rises, drops, recoveries, kind):
    """Notice 2009-94 p. 1: after a peak, declines never lower a 415(d)
    ceiling, and recoveries raise it only past the peak. The IRA kinds use
    the 1(f)(3) base-year ratio instead (see the next test)."""
    _assert_high_water(kind, _q3_levels(rises, drops, recoveries))


def test_high_water_property_rejects_a_peak_dropping_projector():
    """The review's minimized annual-additions path: Q3 rises to 183, then
    falls to 180. A projector that forgets the 2027 peak returns $72,000 for
    2028; the property must reject it."""

    def forgets_peak(year, kind, *, cost_of_living):
        amount, base_year, unit = HIGH_WATER_BASES[kind]
        ratio = max(
            Fraction(1),
            Fraction(cost_of_living.q3_cpi_u[year - 1])
            / Fraction(cost_of_living.q3_cpi_u[base_year]),
        )
        increase = (amount * (ratio - 1)) // unit * unit
        return max(PUBLISHED_2026[kind], int(amount + increase))

    kind = ContributionLimit.ANNUAL_ADDITIONS
    levels = _q3_levels([3], [3], [])
    _assert_high_water(kind, levels)
    with pytest.raises(AssertionError):
        _assert_high_water(kind, levels, limit=forgets_peak)


