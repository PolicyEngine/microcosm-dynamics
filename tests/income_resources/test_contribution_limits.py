@given(ratio=st.integers(17000, 35000))
def test_projection_matches_independent_decimal_formula(ratio):
    """Differential: direct402(g)(4) expression and the generic projector."""
    level = Decimal(ratio) / 100
    path = ContributionCostOfLiving(
        {2005: "100", 2025: "164", 2026: level}, {}, {}
    )
    expected = max(
        24500,
        15000
        + int(
            ((15000 * (level / 100 - 1)) / 500).to_integral_value(
                rounding=ROUND_FLOOR
            )
        )
        * 500,
    )
    assert contribution_limit(
        2027, "elective_deferral", cost_of_living=path
    ) == (expected)


