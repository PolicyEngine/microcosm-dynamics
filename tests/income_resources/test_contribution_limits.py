# Statutory bases, transcribed from the statute rather than parameters.json:
# 402(g)(4) $15,000 from 2005; 414(v)(2)(C) $5,000 from 2005; 415(d)
# $40,000 from 2001 in $1,000 units; 414(v)(2)(E) $11,250 from 2024.
HIGH_WATER_BASES = {
    ContributionLimit.ELECTIVE_DEFERRAL: (15000, 2005, 500),
    ContributionLimit.EMPLOYER_CATCH_UP: (5000, 2005, 500),
    ContributionLimit.ANNUAL_ADDITIONS: (40000, 2001, 1000),
    ContributionLimit.EMPLOYER_CATCH_UP_60_63: (11250, 2024, 500),
}
# Notice 2025-67 pp. 1--2.
PUBLISHED_2026 = {
    ContributionLimit.ELECTIVE_DEFERRAL: 24500,
    ContributionLimit.EMPLOYER_CATCH_UP: 8000,
    ContributionLimit.ANNUAL_ADDITIONS: 72000,
    ContributionLimit.EMPLOYER_CATCH_UP_60_63: 11250,
}


def _q3_levels(rises, drops, recoveries) -> list[int]:
    """INVENTED Q3 CPI-U levels for 2026 on: a peak, declines, a recovery."""
    level, levels = 180, []
    for change in rises:
        level += change
        levels.append(level)
    for change in drops:
        level = max(1, level - change)
        levels.append(level)
    for change in recoveries:
        level += change
        levels.append(level)
    return levels


def _q3_path(levels: list[int]) -> ContributionCostOfLiving:
    """The anchor levels of _invented_path, then the generated levels."""
    q3 = {2001: 100, 2005: 110, 2024: 175, 2025: 180}
    q3.update(enumerate(levels, 2026))
    return ContributionCostOfLiving(
        {year: Decimal(level) for year, level in q3.items()}, {}, {}
    )


def _statutory_ceiling(kind, year, path) -> int:
    """Independent 415(d) reading: floor the increase, keep the high water."""
    amount, base_year, unit = HIGH_WATER_BASES[kind]
    ceiling = PUBLISHED_2026[kind]
    for indexed_year in range(2027, year + 1):
        ratio = max(
            Fraction(1),
            Fraction(path.q3_cpi_u[indexed_year - 1])
            / Fraction(path.q3_cpi_u[base_year]),
        )
        increase = (amount * (ratio - 1)) // unit * unit
        ceiling = max(ceiling, int(amount + increase))
    return ceiling


def _assert_high_water(kind, levels, limit=contribution_limit):
    path = _q3_path(levels)
    reached = PUBLISHED_2026[kind]
    for year in range(2027, 2027 + len(levels)):
        current = limit(year, kind, cost_of_living=path)
        assert current >= reached, (year, current, reached)
        assert current == _statutory_ceiling(kind, year, path)
        reached = current


