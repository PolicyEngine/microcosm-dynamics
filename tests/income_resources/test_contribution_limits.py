def _invented_path(growth: list[int]) -> ContributionCostOfLiving:
    """Invented positive levels at all required bases, then nonnegative COLAs."""
    q3 = {
        2001: Decimal(100),
        2005: Decimal(110),
        2024: Decimal(175),
        2025: Decimal(180),
    }
    annual = {2007: Decimal(100), 2016: Decimal(100)}
    chained = {2016: Decimal(120), 2022: Decimal(160), 2025: Decimal(180)}
    level = Decimal(180)
    for year, increment in enumerate(growth, 2026):
        level += increment
        q3[year] = level
        chained[year] = level
    return ContributionCostOfLiving(q3, annual, chained)


@settings(deadline=None)
@given(
    growth=st.lists(st.integers(0, 30), min_size=1, max_size=12),
    kind=st.sampled_from(list(ContributionLimit)),
)
def test_projected_limits_are_nondecreasing_and_rounded(growth, kind):
    path = _invented_path(growth)
    previous = contribution_limit(2026, kind)
    unit = 1000 if kind == ContributionLimit.ANNUAL_ADDITIONS else 500
    if kind == ContributionLimit.IRA_CATCH_UP:
        unit = 100
    base = 11250 if kind == ContributionLimit.EMPLOYER_CATCH_UP_60_63 else 0
    for year in range(2027, 2027 + len(growth)):
        current = contribution_limit(year, kind, cost_of_living=path)
        assert current >= previous
        assert (current - base) % unit == 0
        previous = current


